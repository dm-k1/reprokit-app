# Tab: "Help: How the App works". How each direction works, every term, every
# result, and the coverage table, which comes straight from
# reprokit::coverage_table() so it always matches what the package does.

mod_help_ui <- function(id) {
  ns <- NS(id)
  page_body(
    page_intro("Help: How the App works",
               paste("How each part works, what every word means, and what can be checked,",
                     "test by test.")),
    layout_columns(
      col_widths = c(6, 6),
      how_it_works_card(
        "I can't share my data", "For authors",
        c("Open your data (or a practice dataset). It stays on your computer.",
          "Pick the test you ran and the columns it used.",
          "Say why the raw data cannot be shared. This is required.",
          paste("Get a verdict, your result recomputed from summary statistics alone, an",
                "appendix to paste into your paper, and what readers lose."))
      ),
      how_it_works_card(
        "Does this paper add up?", "For readers",
        c("Pick the test the paper reports.",
          "Type its numbers exactly as printed; leave out what the paper does not give.",
          "Optionally, say what the paper claims it did (for example Welch's t).",
          paste("See whether the numbers can all be correct together, how much could be",
                "checked, and what is missing."))
      ),
      card(
        card_header("Words the app uses"),
        do.call(accordion, c(
          list(open = FALSE),
          lapply(names(glossary()), function(term) accordion_panel(term, p(glossary()[[term]])))
        ))
      ),
      card(
        card_header("What the results mean"),
        tags$h6("Status of each number"),
        tags$table(class = "table table-sm",
                   tags$tbody(lapply(names(status_info()), function(s) {
                     tags$tr(tags$td(status_badge(s)), tags$td(status_info()[[s]][3L]))
                   }))),
        tags$h6("Coverage level"),
        level_ladder(-1L),
        tags$h6(class = "mt-3", "Verdicts for authors"),
        tags$ul(lapply(verdict_info(), function(v) {
          tags$li(tags$b(paste0(v$icon, " ", v$title, ":")), v$meaning)
        })),
        explain(p(inconsistency_caveat()))
      )
    ),
    card(
      card_header("What reprokit covers, test by test"),
      explain(
        title = "How to read this table",
        tags$ul(
          tags$li(tags$b("apa:"), "what APA style asks a paper to report."),
          tags$li(tags$b("sufficient:"), "what a reader needs to recompute every result."),
          tags$li(tags$b("missing:"), "sufficient minus APA: what an APA-style paper leaves out,",
                  "with the reason. Usually empty for simple tests; it is the paired t-test where",
                  "APA's list stops being enough."),
          tags$li(tags$b("checkable / not_checkable:"), "which APA numbers a reader can recompute",
                  "from the sufficient set, and why the others cannot be."),
          tags$li(tags$b("choices:"), "what the author has to declare because the numbers do not",
                  "reveal it.")
        ),
        p("This table is generated by the package itself, so it cannot disagree with what the",
          "checks actually do.")
      ),
      div(class = "table-responsive", tableOutput(ns("coverage")))
    )
  )
}

# One direction of the app as four numbered steps.
how_it_works_card <- function(title, audience, steps) {
  card(
    card_header(tags$span(tags$b(title), tags$span(class = "text-muted ms-2", audience))),
    tags$ol(class = "how-steps", lapply(steps, tags$li))
  )
}

mod_help_server <- function(id) {
  moduleServer(id, function(input, output, session) {
    output$coverage <- renderTable(reprokit::coverage_table(), striped = TRUE, width = "100%")
  })
}
